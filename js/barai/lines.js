/** نص الصيغة: النص العادي أو الحقل t في الصيغة الموسومة {t, tone, mood}. */
export const textOf = (entry) => (typeof entry === "string" ? entry : (entry && entry.t) || "");
const toneOfEntry = (entry) => (typeof entry === "object" && entry && entry.tone) || null;

/** يستبدل {متغير} بالقيمة؛ وإن غابت قيمة يعيد null حتى لا يظهر نص ناقص. */
export function fill(text, vars = {}) {
  let ok = true;
  const out = String(text).replace(/\{(\w+)\}/g, (m, k) => {
    const v = vars[k];
    if (v === undefined || v === null || v === "") { ok = false; return ""; }
    return String(v);
  });
  return ok ? out : null;
}

const lastIdx = {};
const pickOne = (arr) => arr[Math.floor(Math.random() * arr.length)];

/**
 * يختار صيغة لموقف.
 * opts:
 *   avoid      فهارس لا تُكرَّر (آخر 3 صيغ عبر الجلسات). إن استنفدت كل الصيغ نتجنب الأحدث فقط.
 *   tones      نبرات السياق المناسبة بترتيب الأفضلية (night/slow/gentle/welcome…): الصيغ الموسومة بنبرة
 *              لا تُستخدم إلا إن طابقت، وإن وُجدت مطابقة تُفضَّل بنسبة 75%.
 *   preferName يفضّل صيغة فيها {name} إن وُجدت ومتاحة (يقرره المستدعي ليبقى الاسم نادرًا).
 * يعيد {text, mood, index, usedName} أو null إن لم تتوفر بيانات أي صيغة.
 */
export function pickLine(key, vars = {}, opts = {}) {
  const def = LINES[key];
  if (!def) return null;
  const tones = opts.tones || [];
  const avoid = (opts.avoid || []).concat(lastIdx[key] !== undefined ? [lastIdx[key]] : []);
  const all = [];
  def.texts.forEach((entry, i) => {
    const t = toneOfEntry(entry);
    if (t && !tones.includes(t)) return;
    const f = fill(textOf(entry), vars);
    if (f === null) return;
    all.push({ i, tone: t, usesName: /\{name\}/.test(textOf(entry)) });
  });
  if (!all.length) return null;

  let pool = all;
  const toned = all.filter((x) => x.tone);
  if (toned.length) pool = Math.random() < 0.75 ? toned : (all.filter((x) => !x.tone).length ? all.filter((x) => !x.tone) : toned);

  const named = pool.filter((x) => x.usesName);
  const plain = pool.filter((x) => !x.usesName);
  if (named.length && (!plain.length || (opts.preferName && Math.random() < 0.9))) pool = named;
  else if (plain.length) pool = plain;

  const noRecent = (list, av) => list.filter((x) => !av.includes(x.i));
  let cand = noRecent(pool, avoid);
  if (!cand.length) cand = noRecent(pool, avoid.slice(-1));
  if (!cand.length) cand = pool;
  const pick = pickOne(cand);
  lastIdx[key] = pick.i;
  const entry = def.texts[pick.i];
  return { text: fill(textOf(entry), vars), mood: (typeof entry === "object" && entry.mood) || def.mood, index: pick.i, usedName: pick.usesName };
}
